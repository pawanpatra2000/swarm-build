// Framework output. Agents build every section as HTML + Tailwind (that is what the live preview animates);
// these exporters turn the finished sections into components for the project's own framework.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { themeCSS, fontsHref, slugify } from './assemble.mjs';
import { htmlToJSX } from './export.mjs';

export const TARGETS = ['next', 'react', 'vue', 'nuxt', 'svelte', 'sveltekit', 'astro', 'html'];

// Detects the framework from the nearest package.json. Falls back to plain HTML.
export async function detectTarget(dir = process.cwd()) {
  let cur = path.resolve(dir);
  for (;;) {
    const pj = path.join(cur, 'package.json');
    if (existsSync(pj)) {
      let pkg = {};
      try { pkg = JSON.parse(await readFile(pj, 'utf8')); } catch { /* not JSON */ }
      const deps = { ...pkg.dependencies, ...pkg.devDependencies };
      const has = (n) => Object.prototype.hasOwnProperty.call(deps, n);
      const target = has('next') ? 'next' : has('nuxt') ? 'nuxt' : has('@sveltejs/kit') ? 'sveltekit' : has('astro') ? 'astro'
        : has('svelte') ? 'svelte' : has('vue') ? 'vue' : has('react') ? 'react' : 'html';
      const tailwind = has('tailwindcss') ? (String(deps.tailwindcss).match(/\d+/)?.[0] || '4') : null;
      return { target, root: cur, tailwind, typescript: has('typescript') || existsSync(path.join(cur, 'tsconfig.json')) };
    }
    const up = path.dirname(cur);
    if (up === cur) return { target: 'html', root: path.resolve(dir), tailwind: null, typescript: existsSync(path.join(path.resolve(dir), 'tsconfig.json')) };
    cur = up;
  }
}

const pascal = (id) => id.split(/[^a-zA-Z0-9]+/).filter(Boolean).map((w) => w[0].toUpperCase() + w.slice(1)).join('').replace(/^(\d)/, 'S$1') || 'Section';

// Svelte and Astro read {...} as expressions; Vue reads {{...}}. Keep generated markup literal.
const escapeBraces = (html) => html.replace(/\{/g, '&#123;').replace(/\}/g, '&#125;');

function themeFile(plan) {
  // Scoped to .swarm-page so it never restyles the rest of the user's app.
  const css = themeCSS(plan.theme, plan.design)
    .replace(':root{', '.swarm-page{')
    .replace('html{scroll-behavior:smooth}\n', '')
    .replace('body{', '.swarm-page{')
    .replace('@media (prefers-reduced-motion:reduce){*{', '@media (prefers-reduced-motion:reduce){.swarm-page *{');
  return `/* Shared design tokens and sb-* classes for "${plan.title}". Generated by swarm-build. */\n@import url('${fontsHref(plan.theme)}');\n\n${css}\n`;
}

// Builds the file map for one target. Paths are relative to the project root (or the export folder).
export function filesFor(target, plan, sections, { slug, route, srcDir = '', ts = true, alias = false } = {}) {
  const ids = plan.sections.map((s) => s.id);
  const names = ids.map(pascal);
  const html = (id) => sections[id] || `<section id="${id}"></section>`;
  const head = (s) => `Generated by swarm-build from section "${s.id}" (${s.name}).`;
  const files = {};
  const ext = ts ? 'tsx' : 'jsx';
  const routeSeg = route || slug;

  if (target === 'next') {
    const app = `${srcDir}app`;
    const comp = `${srcDir}components/swarm/${slug}`;
    plan.sections.forEach((s, i) => {
      files[`${comp}/${names[i]}.${ext}`] = `// ${head(s)}\nexport default function ${names[i]}() {\n  return (\n${indent(htmlToJSX(html(s.id)), 4)}\n  );\n}\n`;
    });
    files[`${comp}/swarm-theme.css`] = themeFile(plan);
    const prefix = alias ? `@/components/swarm/${slug}/` : `${'../'.repeat(routeSeg.split('/').length + 1)}components/swarm/${slug}/`;
    files[`${app}/${routeSeg}/page.${ext}`] = `// ${plan.title}. Generated by swarm-build.\n${ts ? "import type { Metadata } from 'next';\n" : ''}import '${prefix}swarm-theme.css';\n${names.map((n) => `import ${n} from '${prefix}${n}';`).join('\n')}\n\nexport const metadata${ts ? ': Metadata' : ''} = {\n  title: ${JSON.stringify(plan.title)},\n  description: ${JSON.stringify(plan.description || '')},\n};\n\nexport default function Page() {\n  return (\n    <main className="swarm-page">\n${names.map((n) => `      <${n} />`).join('\n')}\n    </main>\n  );\n}\n`;
    return files;
  }

  if (target === 'react') {
    const comp = `${srcDir}swarm/${slug}`;
    plan.sections.forEach((s, i) => {
      files[`${comp}/components/${names[i]}.${ext}`] = `// ${head(s)}\nexport default function ${names[i]}() {\n  return (\n${indent(htmlToJSX(html(s.id)), 4)}\n  );\n}\n`;
    });
    files[`${comp}/swarm-theme.css`] = themeFile(plan);
    files[`${comp}/Page.${ext}`] = `// ${plan.title}. Generated by swarm-build. Render <Page /> from your router.\nimport './swarm-theme.css';\n${names.map((n) => `import ${n} from './components/${n}';`).join('\n')}\n\nexport default function Page() {\n  return (\n    <main className="swarm-page">\n${names.map((n) => `      <${n} />`).join('\n')}\n    </main>\n  );\n}\n`;
    return files;
  }

  if (target === 'vue' || target === 'nuxt') {
    const comp = target === 'nuxt' ? `components/swarm/${slug}` : `${srcDir}components/swarm/${slug}`;
    plan.sections.forEach((s, i) => {
      // v-pre: Vue leaves the markup alone (no {{ }} interpolation, no directive parsing).
      const tpl = html(s.id).replace(/^<section\b/i, '<section v-pre');
      files[`${comp}/${names[i]}.vue`] = `<!-- ${head(s)} -->\n<template>\n${indent(tpl, 2)}\n</template>\n`;
    });
    files[`${comp}/swarm-theme.css`] = themeFile(plan);
    const pagePath = target === 'nuxt' ? `pages/${routeSeg}.vue` : `${comp}/Page.vue`;
    const rel = target === 'nuxt' ? `~/components/swarm/${slug}/` : './';
    files[pagePath] = `<!-- ${plan.title}. Generated by swarm-build. -->\n<script setup${ts ? ' lang="ts"' : ''}>\nimport '${rel}swarm-theme.css';\n${names.map((n) => `import ${n} from '${rel}${n}.vue';`).join('\n')}\n</script>\n\n<template>\n  <main class="swarm-page">\n${names.map((n) => `    <${n} />`).join('\n')}\n  </main>\n</template>\n`;
    return files;
  }

  if (target === 'svelte' || target === 'sveltekit') {
    const comp = `${srcDir || 'src/'}lib/swarm/${slug}`;
    plan.sections.forEach((s, i) => {
      files[`${comp}/${names[i]}.svelte`] = `<!-- ${head(s)} -->\n${escapeBraces(html(s.id))}\n`;
    });
    files[`${comp}/swarm-theme.css`] = themeFile(plan);
    const page = `<!-- ${plan.title}. Generated by swarm-build. -->\n<script${ts ? ' lang="ts"' : ''}>\n  import '${target === 'sveltekit' ? `$lib/swarm/${slug}/` : './'}swarm-theme.css';\n${names.map((n) => `  import ${n} from '${target === 'sveltekit' ? `$lib/swarm/${slug}/` : './'}${n}.svelte';`).join('\n')}\n</script>\n\n<svelte:head>\n  <title>${escapeBraces(escapeText(plan.title))}</title>\n</svelte:head>\n\n<main class="swarm-page">\n${names.map((n) => `  <${n} />`).join('\n')}\n</main>\n`;
    files[target === 'sveltekit' ? `${srcDir || 'src/'}routes/${routeSeg}/+page.svelte` : `${comp}/Page.svelte`] = page;
    return files;
  }

  if (target === 'astro') {
    const comp = `${srcDir || 'src/'}components/swarm/${slug}`;
    plan.sections.forEach((s, i) => {
      files[`${comp}/${names[i]}.astro`] = `---\n// ${head(s)}\n---\n${escapeBraces(html(s.id))}\n`;
    });
    files[`${comp}/swarm-theme.css`] = themeFile(plan);
    const depth = routeSeg.split('/').length;
    const rel = `${'../'.repeat(depth)}components/swarm/${slug}/`;
    files[`${srcDir || 'src/'}pages/${routeSeg}.astro`] = `---\n// ${plan.title}. Generated by swarm-build.\nimport '${rel}swarm-theme.css';\n${names.map((n) => `import ${n} from '${rel}${n}.astro';`).join('\n')}\n---\n<html lang="${plan.lang || 'en'}">\n  <head>\n    <meta charset="utf-8" />\n    <meta name="viewport" content="width=device-width, initial-scale=1" />\n    <title>${escapeBraces(escapeText(plan.title))}</title>\n    <meta name="description" content="${escapeText(plan.description || '')}" />\n  </head>\n  <body>\n    <main class="swarm-page">\n${names.map((n) => `      <${n} />`).join('\n')}\n    </main>\n  </body>\n</html>\n`;
    return files;
  }

  throw new Error(`Unknown target "${target}". Use one of: ${TARGETS.join(', ')}.`);
}

const escapeText = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);
const indent = (s, n) => s.split('\n').map((l) => (l ? ' '.repeat(n) + l : l)).join('\n');

// Writes a framework export. With `into`, files go into that project (never overwriting unless force).
export async function exportFramework(run, { target, into, route, force = false } = {}) {
  const plan = await run.plan();
  const sections = Object.fromEntries(await Promise.all(plan.sections.map(async (s) => [s.id, (await run.sectionHTML(s.id)) || ''])));
  const slug = slugify(plan.title).slice(0, 32);
  let info = { target: 'html', root: process.cwd(), tailwind: null, typescript: true };
  if (into || !target || target === 'auto') info = await detectTarget(into || process.cwd());
  const t = !target || target === 'auto' ? info.target : target;
  if (t === 'html') {
    const out = into ? path.join(path.resolve(into), 'public', `${slug}.html`) : run.file('html', 'index.html');
    if (existsSync(out) && !force && into) throw new Error(`${out} exists. Use --force to replace it.`);
    await mkdir(path.dirname(out), { recursive: true });
    await writeFile(out, await readFile(run.file('index.html'), 'utf8'));
    return { target: t, dir: path.dirname(out), files: [out], notes: [] };
  }
  const base = into ? path.resolve(into) : run.file(t);
  const srcDir = into && (t === 'next' || t === 'react' || t === 'vue') && existsSync(path.join(base, 'src')) && !(t === 'next' && existsSync(path.join(base, 'app'))) ? 'src/' : '';
  // Next: use the @/ alias only when tsconfig/jsconfig defines it.
  let alias = false;
  if (t === 'next' && into) {
    for (const f of ['tsconfig.json', 'jsconfig.json']) {
      const p = path.join(base, f);
      if (existsSync(p) && /"@\/\*"/.test(await readFile(p, 'utf8'))) alias = true;
    }
  }
  const ts = into ? info.typescript : true;
  const files = filesFor(t, plan, sections, { slug, route: route || slug, srcDir, ts, alias });
  const clashes = Object.keys(files).filter((f) => existsSync(path.join(base, f)));
  if (clashes.length && !force && into) throw new Error(`These files already exist: ${clashes.join(', ')}. Use --force to replace them or --route to pick another path.`);
  for (const [rel, text] of Object.entries(files)) {
    const p = path.join(base, rel);
    await mkdir(path.dirname(p), { recursive: true });
    await writeFile(p, text);
  }
  const notes = [];
  if (into && !info.tailwind) notes.push('Tailwind CSS was not found in this project. The markup uses Tailwind classes (including arbitrary values like bg-[var(--surface)]); install Tailwind v4 or v3.3+.');
  if (into && info.tailwind === '3') notes.push('Tailwind v3: add the generated folder to `content` in tailwind.config so the classes are generated.');
  notes.push('Forms and buttons have no handlers yet; wire them to your app.');
  const routeNote = { next: `/${route || slug}`, nuxt: `/${route || slug}`, sveltekit: `/${route || slug}`, astro: `/${route || slug}` }[t];
  return { target: t, dir: base, files: Object.keys(files).map((f) => path.join(base, f)), route: routeNote, notes };
}
